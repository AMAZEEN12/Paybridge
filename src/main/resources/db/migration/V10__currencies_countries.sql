-- Intent 001, plan step 2: the currencies PayBridge knows, and the countries whose home currency they are.
-- Adding a currency or a country later is a data change (R-CUR-3): insert a row, no code change.
--
-- The sanctions EXCLUSION list is NOT stored here: it is configuration (paybridge.currencies.excluded) so it can be
-- changed without a migration. An excluded currency is unusable even if it appears in this table (R-CUR-2).
-- The currency list is the starting list from spec section 9 and the country list is a starting mapping. Both must be
-- reviewed before release (R-CUR-4). Symbols with non-ASCII characters use Postgres unicode escapes (U&'\20A6') so the
-- file is safe in any editor encoding.
CREATE TABLE currencies (
                            code         VARCHAR(3)   PRIMARY KEY,
                            name         VARCHAR(60)  NOT NULL,
                            symbol       VARCHAR(8)   NOT NULL,
                            minor_units  SMALLINT     NOT NULL,
                            enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
                            CONSTRAINT ck_currency_code CHECK (code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_currency_minor_units CHECK (minor_units BETWEEN 0 AND 3)
);

CREATE TABLE countries (
                           code           VARCHAR(2)   PRIMARY KEY,
                           name           VARCHAR(80)  NOT NULL,
                           currency_code  VARCHAR(3)   NOT NULL REFERENCES currencies (code),
                           CONSTRAINT ck_country_code CHECK (code ~ '^[A-Z]{2}$')
    );
CREATE INDEX ix_countries_currency ON countries (currency_code);

